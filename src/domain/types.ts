// Domain model for HIRONO Collection.
// Catalog data (shared, published as static JSON) is kept strictly separate
// from personal data (collection, wishlist, photos, settings) which never
// leaves the device unless the user exports it.

export const SCHEMA_VERSION = 1;

export const VERIFICATION_STATUSES = [
  'VERIFIED_OFFICIAL',
  'VERIFIED_CROSS_REFERENCED',
  'UNVERIFIED',
  'NEEDS_REVIEW',
] as const;
export type VerificationStatus = (typeof VERIFICATION_STATUSES)[number];

export const SOURCE_TYPES = [
  'OFFICIAL_POPMART',
  'BRAND_ANNOUNCEMENT',
  'ARTIST',
  'COLLECTOR_REFERENCE',
  'SECONDARY',
  'USER',
] as const;
export type SourceType = (typeof SOURCE_TYPES)[number];

export const CATEGORIES = [
  'MAIN_BLIND_BOX',
  'COLLABORATION',
  'LIMITED_SPECIAL',
  'LARGE_FIGURE',
  'PLUSH_ACCESSORY',
  'OTHER',
] as const;
export type Category = (typeof CATEGORIES)[number];

export const EDITION_TYPES = ['REGULAR', 'SECRET', 'SUPER_SECRET', 'SPECIAL', 'SINGLE'] as const;
export type EditionType = (typeof EDITION_TYPES)[number];

export const ROSTER_STATUSES = ['COMPLETE', 'PARTIAL', 'UNKNOWN'] as const;
export type RosterStatus = (typeof ROSTER_STATUSES)[number];

export interface Source {
  id: string;
  title: string;
  source_type: SourceType;
  publisher: string;
  url: string;
  published_at: string | null;
  accessed_at: string;
  notes: string;
}

export interface SourceRef {
  source_id: string;
  /** What this source confirms, e.g. "Style name listed on the official page". */
  confirms: string;
}

export interface Series {
  id: string;
  slug: string;
  name_en: string;
  name_th: string | null;
  release_year: number | null;
  release_date: string | null;
  series_type: Category;
  product_kind: string;
  description: string | null;
  cover_image: string | null;
  verification_status: VerificationStatus;
  /** Whether the list of styles in this series is known to be complete. */
  roster_status: RosterStatus;
  declared_count: { regular: number | null; secret: number | null };
  sources: SourceRef[];
  conflicts: string[];
  origin?: 'catalog' | 'local';
  archived?: boolean;
  created_at: string;
  updated_at: string;
}

export interface Item {
  id: string;
  slug: string;
  name_en: string;
  name_th: string | null;
  series_id: string | null;
  category: Category;
  subcategory: string | null;
  release_year: number | null;
  release_date: string | null;
  edition_type: EditionType;
  rarity: string | null;
  product_code: string | null;
  description: string | null;
  images: string[];
  verification_status: VerificationStatus;
  sources: SourceRef[];
  conflicts: string[];
  aliases: string[];
  /** Removed from the published catalog. Kept so personal entries still resolve. */
  archived: boolean;
  /** 'catalog' rows come from the published dataset; 'local' rows were added on this device. */
  origin: 'catalog' | 'local';
  /** Set on this device when the user flags the entry as wrong or cancelled. */
  local_flag?: 'WRONG_INFO' | 'CANCELLED' | null;
  created_at: string;
  updated_at: string;
}

export interface CatalogFile {
  schema_version: number;
  catalog_version: string;
  generated_at: string;
  last_verified_at: string;
  coverage: { total_universe_known: boolean; notes: string };
  sources: Source[];
  series: Series[];
  items: Item[];
}

export interface CatalogMeta {
  key: 'catalog';
  catalog_version: string;
  schema_version: number;
  installed_at: string;
  last_verified_at: string;
  origin: 'bundled' | 'remote' | 'file';
  coverage: CatalogFile['coverage'];
}

// ---------- personal data ----------

export const COLLECTION_STATUSES = ['NOT_OWNED', 'WISHLIST', 'ORDERED', 'OWNED', 'TRADE_OR_SELL'] as const;
export type CollectionStatus = (typeof COLLECTION_STATUSES)[number];

export const CONDITIONS = ['NEW_SEALED', 'OPENED_MINT', 'GOOD', 'FAIR', 'DAMAGED'] as const;
export type Condition = (typeof CONDITIONS)[number];

export const PRESENCE = ['UNKNOWN', 'YES', 'NO'] as const;
export type Presence = (typeof PRESENCE)[number];

export interface CollectionEntry {
  /** One entry per catalog item: item_id is the primary key, so duplicates cannot exist. */
  item_id: string;
  status: CollectionStatus;
  quantity: number;
  /** Price paid per piece. */
  purchase_price: number | null;
  /** User's own estimate of the current value per piece. Never generated by the app. */
  estimated_value: number | null;
  acquired_date: string | null;
  condition: Condition | null;
  box_status: Presence;
  card_status: Presence;
  accessories_status: Presence;
  store: string | null;
  personal_notes: string | null;
  is_favorite: boolean;
  created_at: string;
  updated_at: string;
}

export interface StatusEvent {
  id: string;
  item_id: string;
  from_status: CollectionStatus | null;
  to_status: CollectionStatus;
  from_quantity: number;
  to_quantity: number;
  at: string;
}

export const PRIORITIES = [1, 2, 3] as const;
export type Priority = (typeof PRIORITIES)[number];

export interface WishlistEntry {
  item_id: string;
  target_price: number | null;
  last_seen_price: number | null;
  priority: Priority;
  notes: string | null;
  store_url: string | null;
  created_at: string;
  updated_at: string;
}

export interface Photo {
  id: string;
  item_id: string;
  blob: Blob;
  width: number;
  height: number;
  created_at: string;
}

export interface CatalogEditEvent {
  id: string;
  target: 'item' | 'series' | 'catalog';
  target_id: string;
  action: 'create' | 'update' | 'archive' | 'flag' | 'import' | 'catalog_update';
  summary: string;
  at: string;
}

export interface Profile {
  display_name: string;
  bio: string;
  avatar_data_url: string | null;
}

export interface Settings {
  key: 'settings';
  theme: 'system' | 'light' | 'dark';
  display_currency: string;
  collection_sort: 'updated' | 'name' | 'year' | 'added';
  hide_values: boolean;
  explore_view: 'grid' | 'list';
  profile: Profile;
  last_backup_at: string | null;
  last_backup_count: number | null;
  recently_viewed: string[];
  install_hint_dismissed: boolean;
}

